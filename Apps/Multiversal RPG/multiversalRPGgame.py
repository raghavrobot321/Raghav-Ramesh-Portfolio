# Basic Attack
def boss_normal_attack(boss, heroA, heroB):
    # Randomize hero to attack
    if heroA[2] > 0 and heroB[2] > 0:
        if rand.random() < 0.5:
            target = heroA
        else:
            target = heroB
    # Only attack alive hero
    else:
        if heroA[2] > 0:
            target = heroA
        else:
            target = heroB

    # Miss chance
    if target[2] <= 0:
        return boss[0] + " swings angrily but hits no one. (｡•́︿•̀｡)"

    # Randomize damage
    dmg = rand.randint(8, 15) + boss[3] - target[6]

    # Take hero health
    if dmg < 1:
        dmg = 9
    target[2] -= dmg
    sound.PlaySound(boss_attack_sound, sound.SND_FILENAME)
    return boss[0] + " attacks " + target[0] + "! 💪 (-" + str(dmg) + " HP)"

