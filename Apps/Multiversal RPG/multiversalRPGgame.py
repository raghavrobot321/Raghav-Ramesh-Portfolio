# Check for current universe (meant for boss creation)
def get_universe_index(universe):
    universes = ["Superhero", "Space", "Goofy", "Horror", "War", "Digital", "Mature Dark", "Cartoon", "Medieval"]
    return universes.index(universe)

#-----Boss Creation-----

def create_boss(hero, difficulty):
    universe_index = get_universe_index(hero[1])
    boss_name = boss_names[universe_index]

    # Boss HP set by difficulty chosen
    if difficulty == "1":      # Easy
        base_hp = 160
    elif difficulty == "2":    # Normal
        base_hp = 200
    else:                      # Hard
        base_hp = 260

    # Boss stats format set:
    # [name, universe, hp, buff, debuff]
    return [boss_name, hero[1], base_hp, 0, 0]

