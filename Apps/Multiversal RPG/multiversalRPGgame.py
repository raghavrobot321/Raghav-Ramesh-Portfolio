# Ask to pick out heroes
def pick_hero(heroes_list, blocked_universe = ""):
    print()
    print("--- HERO SELECTION ----")
    allowed = []

    # Filter out heroes from the same universe as the first pick
    for hero in heroes_list:
        if hero[1] != blocked_universe:
            allowed.append(hero)

    # Display heroes
    for i in range(len(allowed)):
        hero = allowed[i]
        print(str(i+1) + ". " + hero[0] + " (" + hero[1] + ") -- HP: " + str(hero[2]))
    print()

    # Input confirmation
    choice = ""
    while True:
        choice = input("Choose a hero: ")
        if choice.isdigit():
            index = int(choice) - 1
            if 0 <= index < len(allowed):
                return allowed[index]
        print("Invalid choice. Please enter one of the numbers shown. ❌")


# Hero Turns
def hero_turn(hero, boss, heroes):

    # If stunned, skip turn
    if hero[9] > 0:
        print("\n--- " + hero[0] + " is stunned and cannot move! (𖦹ᯅ𖦹) ---")
        hero[9] -= 1
        return hero[0] + " is stunned. (𖦹ᯅ𖦹)"

    print("\n--- " + hero[0] + "'s Turn ---")
    print("1. Use Power: " + hero[4] + " (CD: " + str(hero[12]) + ")")
    print("2. Basic Attack (-5 to -10 HP)")
    print("3. Special Move: " + hero[11] + " (CD: " + str(hero[13]) + ")")

    choice = ""
    while choice not in ["1", "2", "3"]:
        choice = input("Choose action ⭐: ")
        if choice not in ["1", "2", "3"]:
            print("Please enter 1, 2, or 3.")

    # POWER MOVE (with cooldown)
    if choice == "1":
        if hero[12] > 0:
            return hero[0] + " cannot use " + hero[4] + " yet! (" + str(hero[12]) + " turns left)"
        hero[12] = 3  # Power cooldown (Option C)
        result = hero[3](hero, boss)

        # Reduce cooldowns after action
        if hero[12] > 0:
            hero[12] -= 1
        if hero[13] > 0:
            hero[13] -= 1

        return result

    # BASIC ATTACK (no cooldown)
    if choice == "2":
        dmg = rand.randint(6, 10) + hero[6] - boss[4]
        if dmg < 1:
            dmg = 1
        boss[2] -= dmg
        sound.PlaySound(attack_sound, sound.SND_FILENAME)

        # Reduce cooldowns after action
        if hero[12] > 0:
            hero[12] -= 1
        if hero[13] > 0:
            hero[13] -= 1

        return hero[0] + " hits with a basic attack! 👊 (-" + str(dmg) + " HP)"

    # SPECIAL MOVE (with cooldown)
    if choice == "3":
        if hero[13] > 0:
            return hero[0] + " cannot use " + hero[11] + " yet! (" + str(hero[13]) + " turns left)"
        hero[13] = 3   # Special cooldown (Option A)
        result = hero[10](hero, boss, heroes)

        # Reduce cooldowns after action
        if hero[12] > 0:
            hero[12] -= 1
        if hero[13] > 0:
            hero[13] -= 1

        return result


