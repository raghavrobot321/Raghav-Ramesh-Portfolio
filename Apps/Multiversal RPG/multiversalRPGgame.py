#-----Boss Turn-----
def boss_turn(boss, heroA, heroB):

    # Both heroes are dead
    if heroA[2] <= 0 and heroB[2] <= 0:
        return boss[0] + " stands over the fallen heroes. ( ◡̀_◡́)ᕤ"

    # Randomize boss moves
    boss_chance = rand.random()

    # Chance to do different abilities based on chance
    if boss_chance < 0.25:
        return boss_normal_attack(boss, heroA, heroB)
    elif boss_chance < 0.50:
        return boss_multi_attack(boss, heroA, heroB)
    elif boss_chance < 0.75:
        return boss_enrage(boss)
    elif boss_chance < 0.85:
        return boss_stun(boss, heroA, heroB)
    elif boss_chance < 0.99:
        return boss_fear(boss, heroA, heroB)
    else:
        return boss_instakill(boss, heroA, heroB)

